import "@testing-library/jest-dom";

// O jsdom não implementa matchMedia; o Chakra usa para os breakpoints (useBreakpointValue).
if (!window.matchMedia) {
  window.matchMedia = (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  });
}
